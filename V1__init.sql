-- Початкова структура бази даних college
-- Практична робота №8

CREATE SCHEMA IF NOT EXISTS college;

CREATE TABLE college.departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name TEXT NOT NULL
);

CREATE TABLE college.publishers (
    publisher_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publisher_name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE college.authors (
    author_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name VARCHAR(150) NOT NULL
);

CREATE TABLE college.readers (
    reader_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE
);

CREATE TABLE college.books (
    book_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    publisher_id INTEGER,
    publication_year INTEGER,
    CONSTRAINT fk_books_publisher
        FOREIGN KEY (publisher_id)
        REFERENCES college.publishers(publisher_id),
    CONSTRAINT chk_books_year
        CHECK (publication_year IS NULL OR publication_year > 0)
);

CREATE TABLE college.book_authors (
    book_id INTEGER NOT NULL,
    author_id INTEGER NOT NULL,
    CONSTRAINT pk_book_authors
        PRIMARY KEY (book_id, author_id),
    CONSTRAINT fk_book_authors_book
        FOREIGN KEY (book_id)
        REFERENCES college.books(book_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_book_authors_author
        FOREIGN KEY (author_id)
        REFERENCES college.authors(author_id)
        ON DELETE CASCADE
);

CREATE TABLE college.copies (
    copy_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL,
    inventory_number VARCHAR(50) NOT NULL UNIQUE,
    CONSTRAINT fk_copies_book
        FOREIGN KEY (book_id)
        REFERENCES college.books(book_id)
);

CREATE TABLE college.courses (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INTEGER NOT NULL,
    course_name VARCHAR(100) NOT NULL,
    credits SMALLINT NOT NULL,
    tuition_fee NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_courses_department
        FOREIGN KEY (department_id)
        REFERENCES college.departments(department_id),
    CONSTRAINT chk_courses_credits
        CHECK (credits BETWEEN 1 AND 30),
    CONSTRAINT chk_courses_tuition_fee
        CHECK (tuition_fee >= 0)
);

CREATE TABLE college.enrollments (
    student_id INTEGER NOT NULL,
    course_id INTEGER NOT NULL,
    enrollment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_enrollments
        PRIMARY KEY (student_id, course_id),
    CONSTRAINT fk_enrollments_course
        FOREIGN KEY (course_id)
        REFERENCES college.courses(course_id)
);

CREATE TABLE college.loans (
    loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id INTEGER NOT NULL,
    copy_id INTEGER NOT NULL,
    loan_date DATE NOT NULL DEFAULT CURRENT_DATE,
    return_date DATE,
    CONSTRAINT fk_loans_reader
        FOREIGN KEY (reader_id)
        REFERENCES college.readers(reader_id),
    CONSTRAINT fk_loans_copy
        FOREIGN KEY (copy_id)
        REFERENCES college.copies(copy_id),
    CONSTRAINT chk_loans_dates
        CHECK (return_date IS NULL OR return_date >= loan_date)
);