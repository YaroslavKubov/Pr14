-- Додавання викладача до курсів

BEGIN;

CREATE TABLE college.teachers (
    teacher_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL
);

INSERT INTO college.teachers (full_name)
VALUES ('Викладач за замовчуванням');

ALTER TABLE college.courses
ADD COLUMN teacher_id INTEGER;

UPDATE college.courses
SET teacher_id = (
    SELECT teacher_id
    FROM college.teachers
    LIMIT 1
);

ALTER TABLE college.courses
ALTER COLUMN teacher_id SET NOT NULL;

ALTER TABLE college.courses
ADD CONSTRAINT fk_courses_teacher
FOREIGN KEY (teacher_id)
REFERENCES college.teachers(teacher_id);

COMMIT;

